/**
 * End-to-end workflow test for CredVault.
 *
 * Boots the compiled server against a throwaway SQLite file and exercises every
 * major workflow over real HTTP: application submission, tracking, admin login,
 * authentication guards, approval, certificate issuance, verification, rejection
 * and revocation.
 *
 * Usage: npm test   (builds first, then runs this script)
 */
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const PORT = Number(process.env.SMOKE_PORT || 4317);
const BASE = `http://127.0.0.1:${PORT}`;
const TMP_DIR = fs.mkdtempSync(path.join(os.tmpdir(), 'credvault-smoke-'));
const DB_PATH = path.join(TMP_DIR, 'smoke.sqlite');

const ADMIN_EMAIL = 'admin@smoke.test';
const ADMIN_PASSWORD = 'SmokeTest@2025';

let passed = 0;
const failures = [];

function check(name, condition, detail) {
  if (condition) {
    passed += 1;
    console.log(`PASS  ${name}`);
  } else {
    const line = detail ? `${name} — ${detail}` : name;
    failures.push(line);
    console.log(`FAIL  ${line}`);
  }
}

async function request(method, pathname, { token, body } = {}) {
  const headers = {};
  if (body !== undefined) headers['Content-Type'] = 'application/json';
  if (token) headers.Authorization = `Bearer ${token}`;
  const res = await fetch(`${BASE}${pathname}`, {
    method,
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const text = await res.text();
  let data = null;
  try {
    data = text ? JSON.parse(text) : null;
  } catch {
    data = text;
  }
  return { status: res.status, data };
}

async function waitForServer(timeoutMs = 30000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(`${BASE}/api/health`);
      if (res.ok) return true;
    } catch {
      /* server not up yet */
    }
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  return false;
}

const SAMPLE = {
  full_name: 'Ananya Sharma',
  phone: '+91 98765 43210',
  gender: 'female',
  city: 'Bengaluru',
  state: 'Karnataka',
};

async function run() {
  console.log('--- CredVault workflow test ---');
  console.log(`database: ${DB_PATH}`);

  const server = spawn(process.execPath, ['dist/index.js'], {
    cwd: path.resolve(__dirname, '..'),
    env: {
      ...process.env,
      NODE_ENV: 'test',
      PORT: String(PORT),
      DB_PATH,
      JWT_SECRET: 'smoke-test-secret-key',
      ADMIN_EMAIL,
      ADMIN_PASSWORD,
      ADMIN_NAME: 'Smoke Test Admin',
    },
    stdio: ['ignore', 'pipe', 'pipe'],
  });

  const serverLog = [];
  server.stdout.on('data', (chunk) => serverLog.push(chunk.toString()));
  server.stderr.on('data', (chunk) => serverLog.push(chunk.toString()));

  try {
    const ready = await waitForServer();
    if (!ready) {
      console.log(serverLog.join(''));
      throw new Error('Server did not become ready in time.');
    }

    /* ---------------------------------------------------------- health -- */
    const health = await request('GET', '/api/health');
    check('health endpoint responds', health.status === 200 && health.data.status === 'ok', `status ${health.status}`);

    /* ------------------------------------------------- application flow -- */
    const invalid = await request('POST', '/api/applications', { body: { ...SAMPLE, phone: '12345' } });
    check('invalid application is rejected with field errors', invalid.status === 400 && Boolean(invalid.data?.error?.errors?.phone), JSON.stringify(invalid.data));

    const created = await request('POST', '/api/applications', { body: SAMPLE });
    const applicationId = created.data?.application?.application_id;
    check('application submitted and stored', created.status === 201 && Boolean(applicationId), `status ${created.status}`);
    check('application ID generated by backend', typeof applicationId === 'string' && /^APP-\d{4}-[A-Z0-9]{6}$/.test(applicationId), applicationId);
    check('new application starts as pending', created.data?.application?.status === 'pending', created.data?.application?.status);
    check('phone number normalised to 10 digits', created.data?.application?.phone === '9876543210', created.data?.application?.phone);

    const tracked = await request('GET', `/api/applications/${applicationId}`);
    check('application can be tracked by ID', tracked.status === 200 && tracked.data.application.application_id === applicationId, `status ${tracked.status}`);

    const missingApplication = await request('GET', '/api/applications/APP-2024-ZZZZZZ');
    check('unknown application ID returns 404 message', missingApplication.status === 404 && typeof missingApplication.data?.error?.message === 'string', `status ${missingApplication.status}`);

    /* ------------------------------------------------------ admin auth -- */
    const guarded = await request('GET', '/api/admin/applications');
    check('admin API rejects unauthenticated request', guarded.status === 401, `status ${guarded.status}`);

    const forged = await request('GET', '/api/admin/applications', { token: 'not-a-real-token' });
    check('admin API rejects forged token', forged.status === 401, `status ${forged.status}`);

    const badLogin = await request('POST', '/api/admin/login', {
      body: { email: ADMIN_EMAIL, password: 'wrong-password' },
    });
    check('wrong admin password is rejected', badLogin.status === 401, `status ${badLogin.status}`);

    const login = await request('POST', '/api/admin/login', {
      body: { email: ADMIN_EMAIL, password: ADMIN_PASSWORD },
    });
    const token = login.data?.token;
    check('admin login returns a JWT', login.status === 200 && typeof token === 'string' && token.split('.').length === 3, `status ${login.status}`);

    const me = await request('GET', '/api/admin/me', { token });
    check('JWT authenticates protected /me route', me.status === 200 && me.data.admin.email === ADMIN_EMAIL, `status ${me.status}`);

    const list = await request('GET', '/api/admin/applications', { token });
    check('admin sees submitted applications', list.status === 200 && list.data.applications.some((row) => row.application_id === applicationId), `status ${list.status}`);

    const filteredPending = await request('GET', '/api/admin/applications?status=pending', { token });
    check('admin status filter works', filteredPending.status === 200 && filteredPending.data.applications.every((row) => row.status === 'pending'), 'non-pending row returned');

    const searched = await request('GET', '/api/admin/applications?q=ananya', { token });
    check('admin search by name works', searched.status === 200 && searched.data.applications.length >= 1, `status ${searched.status}`);

    /* ------------------------------------------------- issue certificate -- */
    const earlyIssue = await request('POST', `/api/admin/applications/${applicationId}/certificate`, { token });
    check('certificate cannot be issued before approval', earlyIssue.status === 409, `status ${earlyIssue.status}`);

    const approved = await request('PATCH', `/api/admin/applications/${applicationId}`, {
      token,
      body: { status: 'approved', remarks: 'Documents verified during review.' },
    });
    check('admin can approve an application', approved.status === 200 && approved.data.application.status === 'approved', `status ${approved.status}`);
    check('reviewer is recorded on the application', approved.data?.application?.reviewed_by === ADMIN_EMAIL, approved.data?.application?.reviewed_by);

    const issued = await request('POST', `/api/admin/applications/${applicationId}/certificate`, { token });
    const certificateId = issued.data?.certificate?.certificate_id;
    check('certificate issued for approved application', issued.status === 201 && Boolean(certificateId), `status ${issued.status}`);
    check('certificate ID generated by backend', typeof certificateId === 'string' && /^CERT-\d{4}-[A-Z0-9]{7}$/.test(certificateId), certificateId);

    const duplicateIssue = await request('POST', `/api/admin/applications/${applicationId}/certificate`, { token });
    check('duplicate issuance is blocked', duplicateIssue.status === 409, `status ${duplicateIssue.status}`);

    /* --------------------------------------------------------- verify -- */
    const verified = await request('GET', `/api/certificates/${certificateId}`);
    check('certificate verifies as valid', verified.status === 200 && verified.data.certificate.status === 'valid', `status ${verified.status}`);
    check('verification returns genuine holder details', verified.data?.certificate?.full_name === SAMPLE.full_name && verified.data?.certificate?.city === SAMPLE.city, JSON.stringify(verified.data?.certificate));
    check('verification masks the phone number', verified.data?.certificate?.masked_phone === '******3210', verified.data?.certificate?.masked_phone);

    const unknownCertificate = await request('GET', '/api/certificates/CERT-2024-NOTREAL');
    check('unknown certificate ID returns a clear 404', unknownCertificate.status === 404 && /not found/i.test(unknownCertificate.data?.error?.message ?? ''), `status ${unknownCertificate.status}`);

    /* --------------------------------------------------------- revoke -- */
    const revokeWithoutReason = await request('POST', `/api/admin/certificates/${certificateId}/revoke`, { token, body: {} });
    check('revocation requires a reason', revokeWithoutReason.status === 400, `status ${revokeWithoutReason.status}`);

    const revoked = await request('POST', `/api/admin/certificates/${certificateId}/revoke`, {
      token,
      body: { reason: 'Issued with incorrect candidate details.' },
    });
    check('admin can revoke a certificate', revoked.status === 200 && revoked.data.certificate.status === 'revoked', `status ${revoked.status}`);

    const verifyRevoked = await request('GET', `/api/certificates/${certificateId}`);
    check('verification reports revoked status', verifyRevoked.data?.certificate?.status === 'revoked' && Boolean(verifyRevoked.data?.certificate?.revocation_reason), JSON.stringify(verifyRevoked.data?.certificate));

    /* -------------------------------------------------- rejection flow -- */
    const second = await request('POST', '/api/applications', {
      body: { ...SAMPLE, full_name: 'Rahul Verma', gender: 'male', phone: '9123456780', city: 'Pune', state: 'Maharashtra' },
    });
    const secondId = second.data?.application?.application_id;
    check('second application submitted', second.status === 201 && Boolean(secondId), `status ${second.status}`);

    const rejected = await request('PATCH', `/api/admin/applications/${secondId}`, {
      token,
      body: { status: 'rejected', remarks: 'Photograph did not match the submitted identity proof.' },
    });
    check('admin can reject an application', rejected.status === 200 && rejected.data.application.status === 'rejected', `status ${rejected.status}`);

    const trackRejected = await request('GET', `/api/applications/${secondId}`);
    check('applicant sees rejected status and remarks', trackRejected.data?.application?.status === 'rejected' && Boolean(trackRejected.data?.application?.remarks), JSON.stringify(trackRejected.data?.application));

    const issueRejected = await request('POST', `/api/admin/applications/${secondId}/certificate`, { token });
    check('certificate cannot be issued for rejected application', issueRejected.status === 409, `status ${issueRejected.status}`);

    /* --------------------------------------------------------- listing -- */
    const certificates = await request('GET', '/api/admin/certificates', { token });
    check('admin can list issued certificates', certificates.status === 200 && certificates.data.certificates.some((row) => row.certificate_id === certificateId), `status ${certificates.status}`);

    const revokedOnly = await request('GET', '/api/admin/certificates?status=revoked', { token });
    check('certificate status filter works', revokedOnly.status === 200 && revokedOnly.data.certificates.every((row) => row.status === 'revoked'), 'filter returned non-revoked row');

    const stats = await request('GET', '/api/admin/stats', { token });
    check('admin dashboard stats are computed', stats.status === 200 && stats.data.stats.applications.total >= 2 && stats.data.stats.certificates.revoked >= 1, JSON.stringify(stats.data?.stats));

    const publicStats = await request('GET', '/api/stats');
    check('public stats endpoint responds', publicStats.status === 200 && publicStats.data.stats.certificates >= 1, JSON.stringify(publicStats.data));

    /* -------------------------------------------------------- security -- */
    const unknownApi = await request('GET', '/api/does-not-exist');
    check('unknown API route returns JSON 404', unknownApi.status === 404, `status ${unknownApi.status}`);

    const noCredentialsInLoginBody = JSON.stringify(login.data);
    check('login response never includes the password hash', !/password/i.test(noCredentialsInLoginBody), noCredentialsInLoginBody);
  } finally {
    server.kill('SIGTERM');
    await new Promise((resolve) => setTimeout(resolve, 400));
    if (!server.killed) server.kill('SIGKILL');
  }

  check('database file written to disk', fs.existsSync(DB_PATH) && fs.statSync(DB_PATH).size > 0, DB_PATH);

  console.log('--------------------------------');
  console.log(`${passed} passed, ${failures.length} failed`);
  if (failures.length > 0) {
    console.log('Failures:');
    for (const failure of failures) console.log(` - ${failure}`);
    process.exitCode = 1;
  }

  try {
    fs.rmSync(TMP_DIR, { recursive: true, force: true });
  } catch {
    /* temp cleanup is best effort */
  }
}

run().catch((error) => {
  console.error('Workflow test crashed:', error);
  process.exitCode = 1;
});
